import { cpSync, mkdirSync, readFileSync, writeFileSync, readdirSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { stripTypeScriptTypes } from 'node:module';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const out=join(root,'docs');
// The only cleared directory is this project's generated web output.
rmSync(out,{recursive:true,force:true});mkdirSync(out,{recursive:true});
cpSync(join(root,'web'),out,{recursive:true});
mkdirSync(join(out,'modules'),{recursive:true});mkdirSync(join(out,'data'),{recursive:true});
for(const file of ['srs','strokes'])writeFileSync(join(out,'modules',file+'.mjs'),stripTypeScriptTypes(readFileSync(join(root,'src',file+'.ts'),'utf8')));
if(!readdirSync(join(out,'data')).includes('catalog.json')){
  for(const file of ['words.json','strokes.json'])cpSync(join(root,'src/data',file),join(out,'data',file));
}
cpSync(join(root,'licenses'),join(out,'licenses'),{recursive:true});
cpSync(join(root,'THIRD_PARTY_NOTICES.md'),join(out,'THIRD_PARTY_NOTICES.md'));
writeFileSync(join(out,'.nojekyll'),'');
// Versioned entry assets avoid mixing cached modules with upgraded HTML.
const versionedStudy=source=>source.replace("'./study.mjs'","'./study-v8.mjs'");
writeFileSync(join(out,'app-v8.mjs'),versionedStudy(readFileSync(join(out,'app.mjs'),'utf8')).replace("'./storage.mjs'","'./storage-v8.mjs'").replace("'./audio.mjs'","'./audio-v8.mjs'"));
writeFileSync(join(out,'storage-v8.mjs'),versionedStudy(readFileSync(join(out,'storage.mjs'),'utf8')));
cpSync(join(out,'study.mjs'),join(out,'study-v8.mjs'));
cpSync(join(out,'audio.mjs'),join(out,'audio-v8.mjs'));
cpSync(join(out,'styles.css'),join(out,'styles-v8.css'));
const html=readFileSync(join(out,'index.html'),'utf8').replace('./app.mjs','./app-v8.mjs').replace('./styles.css','./styles-v8.css');
writeFileSync(join(out,'index.html'),html);
writeFileSync(join(out,'study.html'),html);
writeFileSync(join(out,'devices.html'),html);
writeFileSync(join(out,'practice.html'),html);
writeFileSync(join(out,'context.html'),html);
writeFileSync(join(out,'pronunciation.html'),html);
writeFileSync(join(out,'listen.html'),html);
writeFileSync(join(out,'mistakes.html'),html);
const files=['./'];
const hash=createHash('sha256');
function walk(dir){for(const entry of readdirSync(dir,{withFileTypes:true}).sort((a,b)=>a.name<b.name?-1:a.name>b.name?1:0)){const path=join(dir,entry.name);if(entry.isDirectory())walk(path);else{if(!/\.(png|gz|bin)$/.test(path))writeFileSync(path,readFileSync(path,'utf8').replaceAll('\r\n','\n'));files.push('./'+path.slice(out.length+1).replaceAll('\\','/'));hash.update(readFileSync(path));}}}
walk(out);const cache='hanzi-cards-'+hash.digest('hex').slice(0,16);
const sw=`// Generated by scripts/build-web.mjs. All assets are same-origin and offline.
const CACHE=${JSON.stringify(cache)};
const FILES=${JSON.stringify(files)};
self.addEventListener('install',event=>{
  event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(FILES)).then(()=>self.skipWaiting()));
});
self.addEventListener('activate',event=>{
  event.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(key=>key.startsWith('hanzi-cards-')&&key!==CACHE).map(key=>caches.delete(key)))).then(()=>self.clients.claim()));
});
self.addEventListener('fetch',event=>{
  const url=new URL(event.request.url);
  if(event.request.method!=='GET'||url.origin!==self.location.origin||!url.href.startsWith(self.registration.scope))return;
  event.respondWith(caches.open(CACHE).then(async cache=>{
    const cached=await cache.match(event.request,{ignoreSearch:true});
    if(cached)return cached;
    try{return await fetch(event.request);}catch(error){
      if(event.request.mode==='navigate')return cache.match('./index.html');
      throw error;
    }
  }));
});
`;
writeFileSync(join(out,'sw.js'),sw);
console.log(`Built ${files.length} offline entries in docs/ (${cache}).`);
